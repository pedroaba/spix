def fetch(path):
    return subprocess.check_output(['curl', '-fsSL', '--retry', '2', BASE + '/' + urllib.parse.quote(path, safe='/')])

def main():
    target = ROOT / 'design/icons/fluent'
    target.mkdir(parents=True, exist_ok=True)
    def load(item):
        name, (folder, icon, style) = item
        filename = f'ic_fluent_{icon}_24_{style}.svg'
        original = fetch(f'assets/{folder}/SVG/{filename}')
        root = ET.fromstring(original)
        assert root.attrib['viewBox'] == '0 0 24 24', filename
        paths = []
        for path in root:
            assert path.tag.endswith('path'), filename
            assert set(path.attrib).issubset({'d', 'fill', 'fill-rule', 'clip-rule'}), filename
            assert path.get('fill', root.get('fill', '#212121')) in ('#212121', 'currentColor'), filename
            paths.append((path.attrib['d'], path.get('fill-rule') == 'evenodd'))
        (target / filename).write_bytes(original)
        return name, paths
    # Collect every source first; failed requests never partially replace the Kotlin family.
    with ThreadPoolExecutor(max_workers=6) as pool:
        icons = list(pool.map(load, ICONS.items()))
    (target / 'LICENSE').write_bytes(fetch('LICENSE'))
    (target / 'NOTICE').write_bytes(fetch('NOTICE'))
    licenses = ROOT / 'app/src/main/assets/licenses'
    licenses.mkdir(parents=True, exist_ok=True)
    for name in ('LICENSE', 'NOTICE'):
        (licenses / f'fluent-system-icons-{name}.txt').write_bytes((target / name).read_bytes())
    kotlin = '''// Generated by scripts/import_fluent_icons.py. Do not edit paths manually.
// Fluent UI System Icons, Copyright Microsoft Corporation. MIT License.
package com.pedroaba.spix.ui.components

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.PathFillType
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.PathParser
import androidx.compose.ui.unit.dp

/** Official Fluent UI System Icons: Regular 24, with Filled variants for selected navigation. */
object SpixIcons {
    private fun icon(name: String, autoMirror: Boolean = false, vararg paths: Pair<String, Boolean>): ImageVector {
        val builder = ImageVector.Builder(name, 24.dp, 24.dp, 24f, 24f, autoMirror = autoMirror)
        paths.forEach { (path, evenOdd) ->
            builder.addPath(
                pathData = PathParser().parsePathString(path).toNodes(),
                fill = SolidColor(Color.Black),
                pathFillType = if (evenOdd) PathFillType.EvenOdd else PathFillType.NonZero,
            )
        }
        return builder.build()
    }
'''
    for name, paths in icons:
        kotlin += f'\n    val {name} = icon("{name}", {str(name == "Back").lower()},\n'
        for path, even_odd in paths:
            kotlin += f'        {json.dumps(path)} to {str(even_odd).lower()},\n'
        kotlin += '    )\n'
    kotlin += '}\n'
    (ROOT / 'app/src/main/java/com/pedroaba/spix/ui/components/SpixIcons.kt').write_text(kotlin)
    (target / 'README.md').write_text(f'''# Fluent UI System Icons

Official SVGs used by Spix. Source: https://github.com/microsoft/fluentui-system-icons/tree/{COMMIT}

Pinned commit: `{COMMIT}`. Regular 24px with Filled 24px variants for selected navigation.

The original paths and fill rules are preserved in Compose ImageVectors. Tint follows the current theme. The Back icon mirrors for RTL. Only the selected assets are bundled; no complete icon-library dependency is required.

Regenerate with `python3 scripts/import_fluent_icons.py`. `LICENSE` and `NOTICE` are included unchanged from upstream.
''')
    print(f'Imported {len(icons)} official Fluent icons at {COMMIT}.')

if __name__ == '__main__':
    main()
